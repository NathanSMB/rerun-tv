/**
 * MSE wants the byte stream cut into an **initialisation segment** (`ftyp` +
 * `moov`) followed by **media segments** (`moof` + `mdat` pairs). ffmpeg's
 * `frag_keyframe+empty_moov+default_base_moof` output is exactly that shape, but
 * it arrives in arbitrary TCP-sized chunks, so this reassembles it.
 */
export type Mp4Segment =
    | { kind: "init"; data: Uint8Array }
    | { kind: "media"; data: Uint8Array };

export class Mp4SegmentScanner {
    /** Bytes seen but not yet forming a complete box. */
    private pending: Uint8Array = new Uint8Array(0);
    private initParts: Uint8Array[] = [];
    private sawMoov = false;
    /** A `moof` waiting for its `mdat` — the two are appended as one segment. */
    private pendingMoof: Uint8Array | null = null;

    push(chunk: Uint8Array): void {
        this.pending =
            this.pending.length === 0 ? chunk : concat([this.pending, chunk]);
    }

    /**
     * Every segment that has become complete since the last call. Throws
     * `Mp4ParseError` on a stream that isn't the shape we asked ffmpeg for — the
     * caller's cue to fall back to a plain `<video src>` for this episode.
     */
    drain(): Mp4Segment[] {
        const out: Mp4Segment[] = [];
        let at = 0;

        for (;;) {
            const header = readBoxHeader(this.pending, at);
            if (!header || this.pending.length - at < header.size) break;
            const body = this.pending.subarray(at, at + header.size);
            at += header.size;
            this.consume(header.type, body, out);
        }

        // Keep only the incomplete tail. `slice` (a copy) rather than `subarray` so
        // the consumed prefix — up to a whole fragment — becomes collectable.
        if (at > 0) this.pending = this.pending.slice(at);
        return out;
    }

    /** True once the init segment has been emitted. */
    get initialised(): boolean {
        return this.sawMoov;
    }

    private consume(type: string, body: Uint8Array, out: Mp4Segment[]): void {
        if (!this.sawMoov) {
            if (type === "ftyp" || type === "moov") {
                this.initParts.push(body);
                if (type === "moov") {
                    this.sawMoov = true;
                    out.push({ kind: "init", data: concat(this.initParts) });
                    this.initParts = [];
                }
                return;
            }
            if (IGNORED_BOXES.has(type)) return;
            throw new Mp4ParseError(`saw ${type} before the moov box`);
        }

        if (type === "moof") {
            // Two moofs in a row means we lost an mdat, and appending a fragment
            // header with no samples would corrupt the buffer silently.
            if (this.pendingMoof)
                throw new Mp4ParseError("moof with no mdat after it");
            this.pendingMoof = body;
            return;
        }
        if (type === "mdat") {
            if (!this.pendingMoof)
                throw new Mp4ParseError("mdat with no moof before it");
            out.push({ kind: "media", data: concat([this.pendingMoof, body]) });
            this.pendingMoof = null;
            return;
        }
        if (IGNORED_BOXES.has(type)) return;
        throw new Mp4ParseError(`unexpected top-level box ${type}`);
    }
}

