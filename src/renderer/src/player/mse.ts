/**
 * `addSourceBuffer` needs a full MIME type with RFC 6381 codec parameters —
 * `video/mp4; codecs="avc1.640028,mp4a.40.2"`. Chromium will not guess, so the
 * strings have to be derived from the init segment's sample descriptions.
 */
export interface InitSegmentInfo {
    /** e.g. `avc1.640028`. */
    video: string | null;
    /** e.g. `mp4a.40.2`; null for a genuinely silent file. */
    audio: string | null;
    /** What to hand `addSourceBuffer`. */
    mime: string;
}

/** Fixed-field prefix of a `VisualSampleEntry` payload, before its child boxes. */
const VISUAL_ENTRY_PREFIX = 78;
/** Fixed-field prefix of a version-0 `AudioSampleEntry` payload. */
const AUDIO_ENTRY_PREFIX = 28;

const AVC_ENTRY_TYPES = new Set(["avc1", "avc2", "avc3", "avc4"]);

function hex2(byte: number): string {
    return byte.toString(16).padStart(2, "0").toUpperCase();
}

/**
 * `avcC` opens with configurationVersion, then the three bytes RFC 6381 wants
 * verbatim: profile, profile-compatibility, level. `avc1.640028` is High profile
 * at level 4.0 — what our own transcode path produces.
 *
 * The sample entry's own fourcc leads, because `avc1` and `avc3` differ in where
 * parameter sets live and Chromium cares about the distinction.
 */
function avcCodecString(
    entryType: string,
    entryPayload: Uint8Array,
): string | null {
    const avcC = findBox(entryPayload.subarray(VISUAL_ENTRY_PREFIX), "avcC");
    if (!avcC || avcC.payload.length < 4) return null;
    const [, profile, compatibility, level] = avcC.payload;
    return `${entryType}.${hex2(profile)}${hex2(compatibility)}${hex2(level)}`;
}

interface Descriptor {
    tag: number;
    length: number;
    /** Offset of the descriptor's own payload. */
    start: number;
}

/**
 * MPEG-4 descriptors: a tag byte, then a base-128 length of up to four bytes,
 * then the payload. Used only inside `esds`.
 */
function readDescriptor(bytes: Uint8Array, at: number): Descriptor | null {
    if (at < 0 || at >= bytes.length) return null;
    const tag = bytes[at];
    let cursor = at + 1;
    let length = 0;
    for (let byteIndex = 0; byteIndex < 4; byteIndex++) {
        if (cursor >= bytes.length) return null;
        const byte = bytes[cursor++];
        length = (length << 7) | (byte & 0x7f);
        if ((byte & 0x80) === 0) break;
    }
    return { tag, length, start: cursor };
}

const TAG_ES = 0x03;
const TAG_DECODER_CONFIG = 0x04;
const TAG_DECODER_SPECIFIC = 0x05;
/** objectTypeIndication for MPEG-4 audio — i.e. "read the AudioSpecificConfig". */
const OTI_MPEG4_AUDIO = 0x40;
/** MPEG-2 and MPEG-1 Part 3 audio: both are mp3 as far as a codec string goes. */
const OTI_MP3 = new Set([0x69, 0x6b]);
/** Fixed fields of a DecoderConfigDescriptor before its DecoderSpecificInfo. */
const DECODER_CONFIG_PREFIX = 13;

/**
 * Walk `esds` far enough to name the codec: ES descriptor → decoder config →
 * object type, and for MPEG-4 audio one more hop into the AudioSpecificConfig
 * for the audio object type (2 = AAC-LC, which is what everything we produce
 * is, but 5/29 for HE-AAC do turn up in remuxed sources).
 */
function esdsCodecString(esdsPayload: Uint8Array): string | null {
    // esds is a FullBox: skip version + flags.
    const es = readDescriptor(esdsPayload, 4);
    if (!es || es.tag !== TAG_ES) return null;

    let cursor = es.start + 2; // ES_ID
    if (cursor >= esdsPayload.length) return null;
    const flags = esdsPayload[cursor];
    cursor += 1;
    if (flags & 0x80) cursor += 2; // dependsOn_ES_ID
    if (flags & 0x40) cursor += 1 + (esdsPayload[cursor] ?? 0); // URL
    if (flags & 0x20) cursor += 2; // OCR_ES_Id

    const config = readDescriptor(esdsPayload, cursor);
    if (!config || config.tag !== TAG_DECODER_CONFIG) return null;
    if (config.start >= esdsPayload.length) return null;

    const objectType = esdsPayload[config.start];
    if (OTI_MP3.has(objectType)) return "mp4a.6b";
    if (objectType !== OTI_MPEG4_AUDIO) return null;

    let audioObjectType = 2;
    const specific = readDescriptor(
        esdsPayload,
        config.start + DECODER_CONFIG_PREFIX,
    );
    if (
        specific &&
        specific.tag === TAG_DECODER_SPECIFIC &&
        specific.start < esdsPayload.length
    ) {
        const first = esdsPayload[specific.start];
        audioObjectType = first >> 3;
        // 31 is the escape value: the real type is the next six bits, plus 32.
        if (audioObjectType === 31 && specific.start + 1 < esdsPayload.length) {
            audioObjectType =
                32 +
                (((first & 0x07) << 3) |
                    (esdsPayload[specific.start + 1] >> 5));
        }
    }
    return `mp4a.40.${audioObjectType}`;
}

/**
 * The four soundtracks that can reach a `SourceBuffer` from our pipes: AAC (both
 * from the transcode path and from remuxed AAC sources), mp3, Opus and FLAC.
 * Anything else returns null and the episode falls back to plain `src`.
 */
function audioCodecString(
    entryType: string,
    entryPayload: Uint8Array,
): string | null {
    const children = entryPayload.subarray(AUDIO_ENTRY_PREFIX);
    switch (entryType) {
        case "mp4a": {
            const esds = findBox(children, "esds");
            // A missing or unreadable esds is not fatal: `mp4a` in a fragmented MP4 is
            // AAC-LC in every stream we produce, and a wrong guess here would only
            // cost the fallback we were already going to take.
            return (esds && esdsCodecString(esds.payload)) ?? "mp4a.40.2";
        }
        case ".mp3":
        case "mp3 ":
            return "mp4a.6b";
        case "Opus":
        case "opus":
            return "opus";
        case "fLaC":
        case "flac":
            return "flac";
        default:
            return null;
    }
}

/** `mdia/hdlr` names the track kind: `vide`, `soun`, `sbtl`, … */
function handlerType(trakPayload: Uint8Array): string | null {
    const hdlr = descend(trakPayload, ["mdia", "hdlr"]);
    // FullBox version+flags (4) then pre_defined (4), then the handler fourcc.
    if (!hdlr || hdlr.length < 12) return null;
    return readFourCc(hdlr, 8);
}

/** The sample entries inside an `stsd` payload. */
function* sampleEntries(stsdPayload: Uint8Array): Generator<Box> {
    // FullBox version+flags (4) then entry_count (4).
    if (stsdPayload.length < 8) return;
    yield* boxes(stsdPayload.subarray(8));
}

/**
 * Derive the `addSourceBuffer` type from an init segment, or null when the
 * stream is one this parser cannot describe — an exotic remuxed codec, say. Null
 * is a normal outcome, not an error: the caller falls back to a plain
 * `<video src>` for that episode and is then no worse off than before phase 2.
 *
 * A video track is required (these are television episodes); audio is optional,
 * because a silent file is a real thing the remux path serves.
 */
export function parseInitSegment(init: Uint8Array): InitSegmentInfo | null {
    const moov = findBox(init, "moov");
    if (!moov) return null;

    let video: string | null = null;
    let audio: string | null = null;

    for (const box of boxes(moov.payload)) {
        if (box.type !== "trak") continue;
        const kind = handlerType(box.payload);
        if (kind !== "vide" && kind !== "soun") continue;

        const stsd = descend(box.payload, ["mdia", "minf", "stbl", "stsd"]);
        if (!stsd) return null;

        let described = false;
        for (const entry of sampleEntries(stsd)) {
            if (kind === "vide") {
                if (!AVC_ENTRY_TYPES.has(entry.type)) continue;
                const codec = avcCodecString(entry.type, entry.payload);
                if (codec === null) continue;
                video ??= codec;
            } else {
                const codec = audioCodecString(entry.type, entry.payload);
                if (codec === null) continue;
                audio ??= codec;
            }
            described = true;
            break;
        }
        // A track we can see but cannot name would be dropped silently by the
        // browser, so refuse the whole stream and let the fallback handle it.
        if (!described) return null;
    }

    if (video === null) return null;
    const codecs = audio === null ? video : `${video},${audio}`;
    return { video, audio, mime: `video/mp4; codecs="${codecs}"` };
}

/**
 * Video resolution out of the first `avc1`-family sample entry. Not needed for
 * playback — it is here because `tests/mse.test.ts` uses it to prove the box
 * walk is landing on the real sample description rather than on a lucky offset.
 */
export function parseVideoSize(
    init: Uint8Array,
): { width: number; height: number } | null {
    const moov = findBox(init, "moov");
    if (!moov) return null;
    for (const box of boxes(moov.payload)) {
        if (box.type !== "trak" || handlerType(box.payload) !== "vide")
            continue;
        const stsd = descend(box.payload, ["mdia", "minf", "stbl", "stsd"]);
        if (!stsd) return null;
        for (const entry of sampleEntries(stsd)) {
            if (!AVC_ENTRY_TYPES.has(entry.type)) continue;
            // width/height sit 24 bytes into the VisualSampleEntry payload.
            return {
                width: readU16(entry.payload, 24),
                height: readU16(entry.payload, 26),
            };
        }
    }
    return null;
}

