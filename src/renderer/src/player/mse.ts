/** The stream is not the fragmented MP4 we can feed to a `SourceBuffer`. */
export class Mp4ParseError extends Error {
    constructor(message: string) {
        super(message);
        this.name = "Mp4ParseError";
    }
}

const BOX_HEADER_BYTES = 8;

/**
 * Top-level boxes that are legal in the byte stream but carry nothing a
 * `SourceBuffer` needs. `mfra` is the one that actually turns up: ffmpeg writes
 * a fragment random-access index when it closes the file, i.e. right at the end
 * of every episode.
 */
const IGNORED_BOXES = new Set([
    "free",
    "skip",
    "wide",
    "styp",
    "sidx",
    "ssix",
    "mfra",
    "uuid",
]);

function readU16(bytes: Uint8Array, at: number): number {
    return (bytes[at] << 8) | bytes[at + 1];
}

function readU32(bytes: Uint8Array, at: number): number {
    return (
        ((bytes[at] << 24) |
            (bytes[at + 1] << 16) |
            (bytes[at + 2] << 8) |
            bytes[at + 3]) >>>
        0
    );
}

function readFourCc(bytes: Uint8Array, at: number): string {
    return String.fromCharCode(
        bytes[at],
        bytes[at + 1],
        bytes[at + 2],
        bytes[at + 3],
    );
}

interface BoxHeader {
    type: string;
    /** Total box size including the header. */
    size: number;
    /** 8 normally, 16 for the 64-bit `largesize` form. */
    headerSize: number;
}

/**
 * Null means "not enough bytes yet, ask again". A box declaring size 0 ("runs to
 * the end of the file") throws instead: in a live stream we would never learn
 * where it ended, and ffmpeg's fragmented muxer never emits one.
 */
function readBoxHeader(bytes: Uint8Array, at: number): BoxHeader | null {
    if (bytes.length - at < BOX_HEADER_BYTES) return null;
    const declared = readU32(bytes, at);
    const type = readFourCc(bytes, at + 4);

    if (declared === 1) {
        if (bytes.length - at < 16) return null;
        // JS numbers hold this exactly up to 2^53; a media box never approaches it.
        const size = readU32(bytes, at + 8) * 2 ** 32 + readU32(bytes, at + 12);
        if (size < 16)
            throw new Mp4ParseError(
                `box ${type} declares an impossible size ${size}`,
            );
        return { type, size, headerSize: 16 };
    }
    if (declared === 0) {
        throw new Mp4ParseError(
            `box ${type} runs to end-of-file, which a live stream cannot deliver`,
        );
    }
    if (declared < BOX_HEADER_BYTES) {
        throw new Mp4ParseError(
            `box ${type} declares an impossible size ${declared}`,
        );
    }
    return { type, size: declared, headerSize: BOX_HEADER_BYTES };
}

function concat(parts: Uint8Array[]): Uint8Array {
    if (parts.length === 1) return parts[0];
    const total = parts.reduce((sum, part) => sum + part.length, 0);
    const out = new Uint8Array(total);
    let at = 0;
    for (const part of parts) {
        out.set(part, at);
        at += part.length;
    }
    return out;
}

/** One box: `body` is the whole box, `payload` is everything after the header. */
interface Box {
    type: string;
    body: Uint8Array;
    payload: Uint8Array;
}

/** Iterate the boxes laid out back to back in `bytes`. Trailing junk is ignored. */
function* boxes(bytes: Uint8Array): Generator<Box> {
    let at = 0;
    for (;;) {
        let header: BoxHeader | null;
        try {
            header = readBoxHeader(bytes, at);
        } catch {
            return;
        }
        if (!header || bytes.length - at < header.size) return;
        yield {
            type: header.type,
            body: bytes.subarray(at, at + header.size),
            payload: bytes.subarray(at + header.headerSize, at + header.size),
        };
        at += header.size;
    }
}

function findBox(bytes: Uint8Array, type: string): Box | null {
    for (const box of boxes(bytes)) if (box.type === type) return box;
    return null;
}

/** `moov → trak → mdia → minf` style descent, returning the last box's payload. */
function descend(bytes: Uint8Array, path: string[]): Uint8Array | null {
    let current = bytes;
    for (const type of path) {
        const box = findBox(current, type);
        if (!box) return null;
        current = box.payload;
    }
    return current;
}

