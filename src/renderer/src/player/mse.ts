/**
 * MediaSource playback — the pump
 * (docs/playback.md, "The renderer: MediaSource, not `src`").
 *
 * ## Why this module exists
 *
 * A plain `<video src>` hands buffering policy to Chromium's progressive loader.
 * Against a static file that is fine. Against one of our open-ended ffmpeg pipes
 * — no `Content-Length`, `Accept-Ranges: none` — it is the entire bug: when its
 * buffer fills, the loader stops reading, the socket sits zero-window, and
 * Chromium eventually *drops the connection itself* and silently re-requests the
 * same URL. A re-fetch of a file costs milliseconds; a re-fetch of a live
 * transcode restarts ffmpeg at 0:00, so playback freezes until the fresh encode
 * catches back up to the playhead. Deep into an episode that measured 159
 * seconds of dead air.
 *
 * So the renderer fetches the pipe itself and feeds a `MediaSource`. We choose
 * when to read, which means the connection is never abandoned; and we get a real
 * duration, honest `buffered` ranges, and a true end-of-stream for free.
 *
 * ## Why it is DOM-free
 *
 * Everything here talks to structural interfaces (`MediaSourceLike`,
 * `SourceBufferLike`, `ByteReader`) that the real DOM types satisfy. That is not
 * ceremony: it is what lets the box scanner, the codec-string derivation and the
 * whole read/append/evict state machine be unit-tested in `tests/mse.test.ts`
 * against real ffmpeg-generated bytes and a scripted fake reader, in Node, with
 * no browser. The DOM-touching glue — `new MediaSource()`, `fetch`, object URLs —
 * lives in `Player.tsx`, and is the only part that isn't covered.
 *
 * ## The read policy
 *
 * Read until 60s are buffered ahead of the playhead, then stop reading. TCP
 * backpressure throttles ffmpeg exactly as it did before — the difference is
 * that *we* are the ones not reading, so nobody drops the connection. Resume
 * below 15s. Evict anything more than 120s behind the playhead so renderer
 * memory stays flat across a 3-hour session, and on `QuotaExceededError` evict
 * harder and retry rather than failing the stream.
 */

// ---------------------------------------------------------------------------
// Buffer policy
// ---------------------------------------------------------------------------

export interface BufferPolicy {
    /** Stop reading once this many seconds are buffered ahead of the playhead. */
    highWaterS: number;
    /** Start reading again at or below this. Hysteresis, so the reader isn't flapping. */
    lowWaterS: number;
    /** Seconds of already-played media kept behind the playhead. */
    backBufferS: number;
    /** What a `QuotaExceededError` evicts back to before retrying the append. */
    tightBackBufferS: number;
    /** How often a paused reader re-checks whether there is room. */
    pollMs: number;
}

export const DEFAULT_BUFFER_POLICY: BufferPolicy = {
    highWaterS: 60,
    lowWaterS: 15,
    backBufferS: 120,
    tightBackBufferS: 10,
    pollMs: 250,
};

/**
 * A standby pump (phase 3): buffer the first few seconds of the next episode so
 * the handoff is instant, then stop — a hidden element must not sit on 60s of
 * decoded video, and its ffmpeg must not race the one that is actually on air.
 */
export const STANDBY_BUFFER_POLICY: BufferPolicy = {
    ...DEFAULT_BUFFER_POLICY,
    highWaterS: 15,
    lowWaterS: 12,
};

