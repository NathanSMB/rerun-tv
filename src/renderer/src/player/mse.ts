export interface TimeRangesLike {
    readonly length: number;
    start(index: number): number;
    end(index: number): number;
}

/**
 * What `appendBuffer` accepts. Spelled wider than `Uint8Array` deliberately: the
 * DOM's `BufferSource` is pinned to a non-shared `ArrayBuffer`, and this module
 * has to typecheck against both the DOM lib (where the real `SourceBuffer` lives)
 * and the Node lib (where its tests run).
 */
export type AppendData = ArrayBufferView | ArrayBufferLike;

export interface SourceBufferLike {
    readonly updating: boolean;
    readonly buffered: TimeRangesLike;
    appendBuffer(data: AppendData): void;
    remove(start: number, end: number): void;
    addEventListener(type: string, listener: () => void): void;
    removeEventListener(type: string, listener: () => void): void;
}

export interface MediaSourceLike {
    readonly readyState: string;
    duration: number;
    addSourceBuffer(type: string): SourceBufferLike;
    endOfStream(): void;
}

/** Where the playhead is. `HTMLMediaElement` satisfies this. */
export interface MediaClock {
    readonly currentTime: number;
}

/** A `ReadableStreamDefaultReader<Uint8Array>`, structurally. */
export interface ByteReader {
    read(): Promise<{ done: boolean; value?: Uint8Array }>;
    cancel(reason?: unknown): unknown;
}

/** An `AbortSignal`, structurally — the pump only ever reads `aborted`. */
export interface AbortLike {
    readonly aborted: boolean;
}

export interface PumpOptions {
    /**
     * Opens the byte stream. A function rather than a reader so the pump owns the
     * whole lifecycle including the failure of the request itself.
     */
    openReader(): Promise<ByteReader>;
    mediaSource: MediaSourceLike;
    clock: MediaClock;
    /**
     * Episode runtime *minus the seek offset*, so the scrub bar stops guessing.
     * The pipe's own timestamps restart at zero after an `-ss` seek, which is the
     * same reason the Player keeps a display offset.
     */
    durationS?: number | null;
    signal?: AbortLike;
    policy?: Partial<BufferPolicy>;
    /** Read targets `promote()` switches to. Defaults to the full policy. */
    promotedPolicy?: Partial<BufferPolicy>;
    /**
     * The stream defeated the parser. The caller should re-render this episode
     * with a plain `<video src>`; behaviour is then exactly what it was before
     * phase 2, which is worse but not broken.
     */
    onFallback?(reason: string): void;
    /** A real failure: the request died, or the SourceBuffer rejected the data. */
    onError?(error: Error): void;
    /** Test seam. The pump's only wait primitive. */
    sleep?(ms: number): Promise<void>;
}

export interface PumpStats {
    /** False while the reader is parked because the buffer is full. */
    reading: boolean;
    bytes: number;
    /** Media segments appended, not counting the init segment. */
    segments: number;
    /** Back-buffer evictions performed. */
    trims: number;
    /** Appends that hit `QuotaExceededError` and had to evict and retry. */
    quotaRetries: number;
    /** Set once the source has been told the stream is complete. */
    endedStream: boolean;
    fellBack: boolean;
    mime: string | null;
}

export interface Pump {
    readonly stats: PumpStats;
    /** Resolves when the pump stops for any reason: EOF, abort, fallback, error. */
    readonly done: Promise<void>;
    /**
     * Switch to the full read targets. Phase 3's standby pump buffers ~15s while
     * it is hidden and calls this the moment it becomes the picture on screen.
     */
    promote(): void;
    stop(): void;
}

function defaultSleep(ms: number): Promise<void> {
    return new Promise((resolve) => setTimeout(resolve, ms));
}

/** DOMException surfaces this by name; the numeric code is the older spelling. */
function isQuotaExceeded(err: unknown): boolean {
    if (typeof err !== "object" || err === null) return false;
    const candidate = err as { name?: unknown; code?: unknown };
    return candidate.name === "QuotaExceededError" || candidate.code === 22;
}

function isAbort(err: unknown): boolean {
    return (
        typeof err === "object" &&
        err !== null &&
        (err as { name?: unknown }).name === "AbortError"
    );
}

function asError(err: unknown): Error {
    return err instanceof Error ? err : new Error(String(err));
}

/**
 * Start pumping `openReader()`'s bytes into `mediaSource`.
 *
 * The loop is deliberately sequential — read, scan, append, check for room, read
 * again — because every interesting property falls out of that ordering: appends
 * are serialised without an explicit queue (each one is awaited), the reader
 * cannot outrun the buffer, and "stop reading" is simply "don't call `read()`",
 * which is what keeps the connection alive instead of letting Chromium abandon it.
 */
export function startPump(options: PumpOptions): Pump {
    const policy: BufferPolicy = {
        ...DEFAULT_BUFFER_POLICY,
        ...options.policy,
    };
    const promoted: BufferPolicy = {
        ...DEFAULT_BUFFER_POLICY,
        ...options.promotedPolicy,
    };
    const sleep = options.sleep ?? defaultSleep;
    const scanner = new Mp4SegmentScanner();

    const stats: PumpStats = {
        reading: true,
        bytes: 0,
        segments: 0,
        trims: 0,
        quotaRetries: 0,
        endedStream: false,
        fellBack: false,
        mime: null,
    };

    let stopped = false;
    let reader: ByteReader | null = null;
    let sourceBuffer: SourceBufferLike | null = null;

    const aborted = (): boolean => stopped || options.signal?.aborted === true;
    const isOpen = (): boolean => options.mediaSource.readyState === "open";

    // ---- source buffer operations -------------------------------------------

    /**
     * `appendBuffer` and `remove` are both asynchronous and both refuse to start
     * while `updating` — so every operation is awaited to completion. Because the
     * pump is the only thing touching this SourceBuffer, awaiting is the whole
     * queue.
     */
    function operate(run: (sb: SourceBufferLike) => void): Promise<void> {
        const sb = sourceBuffer;
        if (!sb) return Promise.reject(new Error("no source buffer yet"));
        return new Promise<void>((resolve, reject) => {
            const cleanup = (): void => {
                sb.removeEventListener("updateend", onDone);
                sb.removeEventListener("error", onError);
            };
            const onDone = (): void => {
                cleanup();
                resolve();
            };
            const onError = (): void => {
                cleanup();
                // Chromium's MSE demuxer is stricter than its progressive one — it will
                // refuse an init segment the plain-`src` path plays without complaint.
                // So a rejection here is a *parse* failure, which means fall back to
                // plain playback for this episode rather than show a failure card.
                reject(
                    new Mp4ParseError("the source buffer rejected the data"),
                );
            };
            sb.addEventListener("updateend", onDone);
            sb.addEventListener("error", onError);
            try {
                run(sb);
            } catch (err) {
                cleanup();
                reject(err);
            }
        });
    }

    async function waitIdle(): Promise<void> {
        while (sourceBuffer?.updating === true && !aborted())
            await sleep(policy.pollMs);
    }

    /**
     * Evict everything more than `keepS` behind the playhead.
     *
     * Reads `buffered.start(0)` alone because on this path the buffer is always
     * one contiguous range: a seek is a *URL reload* (see `Player.tsx`), never a
     * jump within the stream, so nothing ever appends across a gap. If that ever
     * changes, this has to walk every range instead.
     */
    async function trim(keepS: number): Promise<void> {
        const sb = sourceBuffer;
        if (!sb || sb.buffered.length === 0) return;
        const start = sb.buffered.start(0);
        const cutoff = Math.max(0, options.clock.currentTime - keepS);
        // A hair of slack: removing a sliver every poll would be pure churn.
        if (cutoff - start < 1) return;
        await waitIdle();
        if (aborted()) return;
        await operate((buffer) => buffer.remove(start, cutoff));
        stats.trims += 1;
    }

    /**
     * `QuotaExceededError` is the spec's "buffer is full" and the documented
     * remedy is to evict and retry rather than to fail — a 3-hour session must not
     * end in a broken stream because the back buffer got fat.
     */
    async function append(data: Uint8Array): Promise<void> {
        try {
            await operate((buffer) => buffer.appendBuffer(data));
            return;
        } catch (err) {
            if (!isQuotaExceeded(err)) throw err;
        }
        stats.quotaRetries += 1;
        await trim(policy.tightBackBufferS);
        try {
            await operate((buffer) => buffer.appendBuffer(data));
            return;
        } catch (err) {
            if (!isQuotaExceeded(err)) throw err;
        }
        // Last resort: everything behind the playhead goes.
        await trim(0);
        await operate((buffer) => buffer.appendBuffer(data));
    }

    // ---- read pacing --------------------------------------------------------

    /** Seconds of media buffered ahead of the playhead. */
    function bufferedAhead(): number {
        const sb = sourceBuffer;
        if (!sb) return 0;
        const ranges = sb.buffered;
        const now = options.clock.currentTime;
        for (let i = 0; i < ranges.length; i++) {
            // A shade of tolerance at the start: a fresh stream's first fragment can
            // begin a few milliseconds after zero.
            if (now >= ranges.start(i) - 0.5 && now <= ranges.end(i))
                return ranges.end(i) - now;
        }
        if (ranges.length === 0) return 0;
        // The playhead is outside every range (a seek, or a gap). Measure from the
        // last range so a paused element still stops the reader somewhere sane.
        return Math.max(0, ranges.end(ranges.length - 1) - now);
    }

    /**
     * Park the reader while the buffer is full. Returns once there is room, or
     * once the pump has been stopped.
     *
     * This is the fix, in five lines: not reading is what applies TCP backpressure
     * to ffmpeg — the same throttle the old `<video src>` path relied on — without
     * anybody dropping the connection to achieve it.
     */
    async function waitForRoom(): Promise<void> {
        if (!sourceBuffer) return;
        while (!aborted()) {
            await trim(policy.backBufferS);
            const ahead = bufferedAhead();
            if (stats.reading) {
                if (ahead < policy.highWaterS) return;
                stats.reading = false;
            } else if (ahead <= policy.lowWaterS) {
                stats.reading = true;
                return;
            }
            await sleep(policy.pollMs);
        }
    }

    // ---- segment handling ---------------------------------------------------

    function setDuration(): void {
        const duration = options.durationS;
        if (duration == null || !(duration > 0) || !isOpen()) return;
        try {
            options.mediaSource.duration = duration;
        } catch {
            // Only ever a transient InvalidStateError; the scrub bar falling back to
            // the element's own guess is not worth failing playback over.
        }
    }

    async function consume(segment: Mp4Segment): Promise<void> {
        if (segment.kind === "init") {
            const info = parseInitSegment(segment.data);
            if (!info) {
                throw new Mp4ParseError(
                    "no usable codec string in the initialisation segment",
                );
            }
            stats.mime = info.mime;
            try {
                sourceBuffer = options.mediaSource.addSourceBuffer(info.mime);
            } catch (err) {
                // A codec string we derived correctly but this build cannot decode. Same
                // remedy as a stream we couldn't parse at all: hand the episode back to
                // the plain-`src` path, which at least knows how to ask Chromium.
                throw new Mp4ParseError(
                    `the browser refused codecs ${info.mime}: ${asError(err).message}`,
                );
            }
            await append(segment.data);
            setDuration();
            return;
        }
        if (!sourceBuffer)
            throw new Mp4ParseError(
                "a media fragment arrived before the moov box",
            );
        await append(segment.data);
        stats.segments += 1;
    }

    /** ffmpeg closed the pipe: the episode is complete, so say so. */
    async function finish(): Promise<void> {
        await waitIdle();
        if (aborted() || !isOpen()) return;
        try {
            options.mediaSource.endOfStream();
            stats.endedStream = true;
        } catch {
            // A source already closed by teardown; the element has nothing left to do.
        }
    }

    function fallback(reason: string): void {
        if (stats.fellBack) return;
        stats.fellBack = true;
        options.onFallback?.(reason);
    }

    // ---- the loop -----------------------------------------------------------

    async function run(): Promise<void> {
        try {
            reader = await options.openReader();
        } catch (err) {
            if (!aborted() && !isAbort(err)) options.onError?.(asError(err));
            return;
        }

        try {
            for (;;) {
                await waitForRoom();
                if (aborted()) return;

                const chunk = await reader.read();
                // Abort before EOF: cancelling a reader makes the pending read report
                // `done`, and a torn-down stream must never be called complete.
                if (aborted()) return;
                if (chunk.done) {
                    await finish();
                    return;
                }
                if (!chunk.value || chunk.value.length === 0) continue;

                stats.bytes += chunk.value.length;
                scanner.push(chunk.value);
                for (const segment of scanner.drain()) {
                    await consume(segment);
                    if (aborted()) return;
                }
            }
        } catch (err) {
            if (aborted() || isAbort(err)) return;
            if (err instanceof Mp4ParseError) fallback(err.message);
            else options.onError?.(asError(err));
        } finally {
            // Cancelling closes the socket, which is what tells the stream server to
            // kill this episode's ffmpeg. Never leave that to a garbage collector.
            try {
                await reader?.cancel();
            } catch {
                /* A reader that is already closed or errored has nothing to cancel. */
            }
        }
    }

    const done = run();

    return {
        stats,
        done,
        promote(): void {
            // Every field, not the three that happened to differ: leaving
            // `tightBackBufferS`/`pollMs` behind meant a promoted policy could
            // silently only half-apply, which is invisible until someone sets
            // them to something other than the standby's values.
            Object.assign(policy, promoted);
        },
        stop(): void {
            stopped = true;
            // Don't wait for the read loop to notice: dropping the reader now is what
            // frees the encoder.
            void Promise.resolve(reader?.cancel()).catch(() => undefined);
        },
    };
}
